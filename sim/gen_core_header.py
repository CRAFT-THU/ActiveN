#!/usr/bin/env python3
"""Generate shared simulator Core constants from Core.config.json."""
import argparse
import json
from pathlib import Path


def integer(value, name, minimum=1):
    if isinstance(value, str):
        value = int(value, 0)
    if type(value) is not int or not minimum <= value < 1 << 64:
        raise ValueError(f"{name} must be an integer in [{minimum}, 2**64)")
    return value


def generate(core):
    fields = {
        "SYSTEM_INIT_VEC": integer(core["initVec"], "initVec", 0),
        "SYSTEM_ICACHE_LINES": integer(core["iCacheLines"], "iCacheLines"),
        "SYSTEM_ICACHE_BLOCK_SIZE": integer(core["iCacheBlockSize"], "iCacheBlockSize"),
        "SYSTEM_ICACHE_ASSOC": integer(core["iCacheAssoc"], "iCacheAssoc"),
        "SYSTEM_MEM_BUS_WIDTH": integer(core["memBusWidth"], "memBusWidth"),
        "SYSTEM_SCRATCHPAD_SIZE": integer(core["scratchpadSize"], "scratchpadSize"),
        "SYSTEM_PIPE_CNT": integer(core["pipeCnt"], "pipeCnt"),
    }
    width = fields["SYSTEM_MEM_BUS_WIDTH"]
    if width not in (64, 128, 256, 512):
        raise ValueError("the system simulator supports 64/128/256/512-bit memory lines")
    if type(core["useFPU"]) is not bool:
        raise ValueError("useFPU must be a boolean")
    if not isinstance(core["memCtrlSizes"], list) or not core["memCtrlSizes"]:
        raise ValueError("memCtrlSizes must be a nonempty array")
    sizes = [integer(value, "memCtrlSizes entry") for value in core["memCtrlSizes"]]
    lines = ["// Auto-generated by gen_core_header.py; do not edit",
             "#pragma once", "#include <cstdint>", "",
             "// Compiled Core geometry; PU/MC topology is selected separately.",
             f"inline constexpr int SYSTEM_NUM_MEM_CTRL = {len(sizes)};",
             "inline constexpr uint64_t SYSTEM_MC_SIZES[] = {"
             + ", ".join(f"0x{size:x}" for size in sizes) + "};"]
    for name, value in fields.items():
        ctype = "uint64_t" if name == "SYSTEM_INIT_VEC" else "int"
        lines.append(f"inline constexpr {ctype} {name} = {value};")
    lines += [f"inline constexpr bool SYSTEM_USE_FPU = {'true' if core['useFPU'] else 'false'};",
              "", "// Broadcast accessors for the elaborated memory-line width.",
              "#define SYSTEM_BCAST_SLOT_ENTRIES \\"]
    for slot in range(width // 64):
        suffix = " \\" if slot + 1 < width // 64 else ""
        lines.append(f"    BCAST_SLOT({slot});{suffix}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        content = generate(json.loads(args.config.read_text()))
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    args.output.write_text(content)


if __name__ == "__main__":
    main()
