#!/usr/bin/env python3
"""Generate system_config.h and hard_backend.h from System.config.json."""
import sys, os, json

config_json = sys.argv[1]  # Path to System.config.json
outdir = sys.argv[2]       # Output directory

with open(config_json) as f:
    cfg = json.load(f)

num_pu = cfg["numPU"]
num_mc = cfg["numMC"]
core = cfg["core"]

# ---- system_config.h (legacy, kept for soft backend's SYSTEM_CONFIG) ----
with open(os.path.join(outdir, "system_config.h"), "w") as f:
    f.write("// Auto-generated by gen_system_header.py — do not edit\n")
    f.write("#pragma once\n")
    f.write("#include <cstdint>\n\n")

    # Data constants used by soft backend (no struct definitions — those live in system.h)
    sizes = ", ".join(f"0x{int(s, 16):x}" if isinstance(s, str) else f"0x{s:x}" for s in core["memCtrlSizes"])
    init_vec = int(core["initVec"], 16) if isinstance(core["initVec"], str) else core["initVec"]

    f.write(f"inline constexpr int SYSTEM_NUM_PU = {num_pu};\n")
    f.write(f"inline constexpr int SYSTEM_NUM_MC = {num_mc};\n")
    f.write(f"inline constexpr int SYSTEM_NUM_MEM_CTRL = {len(core['memCtrlSizes'])};\n")
    f.write(f"inline constexpr uint64_t SYSTEM_MC_SIZES[] = {{{sizes}}};\n")
    f.write(f"inline constexpr uint64_t SYSTEM_INIT_VEC = 0x{init_vec:x};\n")
    f.write(f"inline constexpr int SYSTEM_ICACHE_LINES = {core['iCacheLines']};\n")
    f.write(f"inline constexpr int SYSTEM_ICACHE_BLOCK_SIZE = {core['iCacheBlockSize']};\n")
    f.write(f"inline constexpr int SYSTEM_ICACHE_ASSOC = {core['iCacheAssoc']};\n")
    f.write(f"inline constexpr int SYSTEM_MEM_DST = {core['memDst']};\n")
    f.write(f"inline constexpr int SYSTEM_MEM_TAG_BASE = {core['memTagBase']};\n")
    f.write(f"inline constexpr int SYSTEM_MEM_BUS_WIDTH = {core['memBusWidth']};\n")
    f.write(f"inline constexpr int SYSTEM_SCRATCHPAD_SIZE = {core['scratchpadSize']};\n")
    f.write(f"inline constexpr bool SYSTEM_USE_FPU = {'true' if core['useFPU'] else 'false'};\n")
    f.write(f"inline constexpr int SYSTEM_PIPE_CNT = {core['pipeCnt']};\n\n")

    # PU core accessor for SPM preloading (legacy)
    f.write("// Verilator PU core accessors for SPM preloading\n")
    f.write("#define SYSTEM_PU_CASE_ENTRIES \\\n")
    for i in range(1, num_pu + 1):
        f.write(f"    PU_CASE({i});")
        if i < num_pu:
            f.write(" \\")
        f.write("\n")

# ---- hard_backend.h (generated adapter implementing SystemBackend) ----
with open(os.path.join(outdir, "hard_backend.h"), "w") as f:
    f.write("// Auto-generated by gen_system_header.py — do not edit\n")
    f.write("#pragma once\n\n")
    f.write('#include "system.h"\n')
    f.write('#include "sys_verilated/sys_rtl.h"\n')
    f.write('#include <memory>\n')
    f.write('#include <cstring>\n')
    f.write('#include <deque>\n')
    f.write('#include <iostream>\n')
    f.write('#include <verilated.h>\n')
    f.write('#include <verilated_fst_c.h>\n')
    f.write('\n')

    f.write("// Frontend memory (defined in system_new.cpp)\n")
    f.write("extern uint32_t *text_aligned;\n")
    f.write("extern size_t    text_size;\n")
    f.write("void buildMemResp(uint32_t global_addr, uint8_t *data);\n")
    f.write("void applyWrite(uint32_t global_addr, uint8_t size, const uint8_t *wdata);\n\n")

    f.write(f"static constexpr int HARD_NUM_PU = {num_pu};\n")
    f.write(f"static constexpr int HARD_NUM_MC = {num_mc};\n")
    mc_sizes_list = ", ".join(
        f"0x{int(s, 16):x}" if isinstance(s, str) else f"0x{s:x}"
        for s in core["memCtrlSizes"]
    )
    f.write(f"static constexpr uint64_t HARD_MC_SIZES[] = {{{mc_sizes_list}}};\n")
    f.write(f"static constexpr uint64_t HARD_RESET_LENGTH = 10;\n")
    f.write(f"static constexpr uint32_t HARD_TEXT_BASE = 0x80000000u;\n\n")

    # MemPort struct
    f.write("struct HardMemPort {\n")
    f.write("    uint8_t *req_valid;\n")
    f.write("    uint8_t *req_ready;\n")
    f.write("    uint16_t *req_id;\n")
    f.write("    uint32_t *req_addr;\n")
    f.write("    uint32_t *req_wdata; // WData[8]\n")
    f.write("    uint32_t *req_wbe;\n")
    f.write("    uint8_t *req_write;\n")
    f.write("    uint8_t *resp_valid;\n")
    f.write("    uint16_t *resp_id;\n")
    f.write("    uint32_t *resp_rdata; // WData[8]\n")
    f.write("};\n\n")

    f.write("class HardSystemBackend : public SystemBackend {\n")
    f.write("public:\n")
    f.write("    std::unique_ptr<sys_rtl> sys;\n")
    f.write("    uint64_t cycle_ = 0;\n")
    f.write(f"    HardMemPort mem_ports[{num_mc}];\n")
    f.write("    VerilatedFstC *tracer_ = nullptr;\n")
    f.write("    bool tracing_ = false;\n\n")
    f.write("    // Stored requests: captured in Phase 1, reported in mem()\n")
    f.write(f"    std::optional<GlobalMemReq> stored_mc_req_[{num_mc}];\n")
    f.write("    std::optional<GlobalMemReq> stored_periph_req_;\n\n")
    f.write("    // Internal response queues (MC: self-served flat memory; periph: fed from frontend)\n")
    f.write(f"    std::deque<GlobalMemResp> mc_resps_[{num_mc}];\n")
    f.write("    std::deque<GlobalMemResp> periph_resps_;\n")
    f.write(f"    uint64_t mc_bases_[{num_mc}] = {{}};\n\n")

    # Constructor
    f.write("    HardSystemBackend() {\n")
    f.write('        sys.reset(new sys_rtl("system"));\n')
    # Compute MC base offsets
    f.write("        { uint64_t cumul = 0;\n")
    f.write(f"          for (int i = 0; i < {num_mc}; ++i) {{ mc_bases_[i] = cumul; cumul += HARD_MC_SIZES[i]; }}\n")
    f.write("        }\n")
    for i in range(num_mc):
        f.write(f"        mem_ports[{i}].req_valid = &sys->io_mem_{i}_req_valid;\n")
        f.write(f"        mem_ports[{i}].req_ready = &sys->io_mem_{i}_req_ready;\n")
        f.write(f"        mem_ports[{i}].req_id = &sys->io_mem_{i}_req_bits_id;\n")
        f.write(f"        mem_ports[{i}].req_addr = &sys->io_mem_{i}_req_bits_addr;\n")
        f.write(f"        mem_ports[{i}].req_wdata = sys->io_mem_{i}_req_bits_wdata;\n")
        f.write(f"        mem_ports[{i}].req_wbe = &sys->io_mem_{i}_req_bits_wbe;\n")
        f.write(f"        mem_ports[{i}].req_write = &sys->io_mem_{i}_req_bits_write;\n")
        f.write(f"        mem_ports[{i}].resp_valid = &sys->io_mem_{i}_resp_valid;\n")
        f.write(f"        mem_ports[{i}].resp_id = &sys->io_mem_{i}_resp_bits_id;\n")
        f.write(f"        mem_ports[{i}].resp_rdata = sys->io_mem_{i}_resp_bits_rdata;\n")
    f.write("    }\n\n")

    f.write("    ~HardSystemBackend() override { sys->final(); }\n\n")

    f.write("    void attachTrace(VerilatedFstC *t, int depth) {\n")
    f.write("        tracing_ = t != nullptr;\n")
    f.write("        tracer_ = t;\n")
    f.write("        if (t) sys->trace(t, depth);\n")
    f.write("    }\n\n")

    # config()
    f.write("    SystemConfig config() const override {\n")
    f.write("        SystemConfig cfg;\n")
    f.write(f"        cfg.numPU = HARD_NUM_PU;\n")
    f.write(f"        cfg.numMC = HARD_NUM_MC;\n")
    f.write(f"        for (int i = 0; i < HARD_NUM_MC; ++i)\n")
    f.write(f"            cfg.core.mcSizes.push_back(HARD_MC_SIZES[i]);\n")
    f.write("        return cfg;\n")
    f.write("    }\n\n")

    # step(): self-serve memory, matching old SystemModel::stepPosedge timing exactly
    f.write("""    void step(uint64_t cycle) override {
        static constexpr int MEM_BUS_WORDS = MEM_BUS_WIDTH / 32;
        cycle_ = cycle;
        if (cycle_ <= HARD_RESET_LENGTH) {
            sys->reset = true;
""")
    for i in range(num_mc):
        f.write(f"            *mem_ports[{i}].req_ready = 0;\n")
        f.write(f"            *mem_ports[{i}].resp_valid = 0;\n")
    f.write("""            sys->io_periph_req_ready = 0;
            sys->io_periph_resp_valid = 0;
            stored_periph_req_ = std::nullopt;
""")
    f.write(f"            for (int i = 0; i < {num_mc}; ++i) stored_mc_req_[i] = std::nullopt;\n")
    f.write("""            sys->clock = true;
            Verilated::timeInc(1);
            sys->eval();
            if (tracing_ && tracer_) tracer_->dump(cycle_ * 2);
            sys->clock = false;
            Verilated::timeInc(1);
            sys->eval();
            if (tracing_ && tracer_) tracer_->dump(cycle_ * 2 + 1);
            return;
        }

        // ── Phase 1: Capture + serve + pop consumed ──
        // (matches old SystemModel::stepPosedge Phase 1)

        // MC requests
        for (int mc = 0; mc < HARD_NUM_MC; ++mc) {
            auto &p = mem_ports[mc];
            if (*p.req_ready && *p.req_valid) {
                GlobalMemReq req{};
                req.id = *p.req_id;
                req.addr = *p.req_addr;
                req.write = *p.req_write;
                req.size = 5;
                std::memcpy(req.wdata, p.req_wdata, MEM_BUS_WORDS * 4);
                stored_mc_req_[mc] = req;

                // Self-serve from frontend's flat memory
                uint32_t global_addr = req.addr + HARD_TEXT_BASE + (uint32_t)mc_bases_[mc];
                GlobalMemResp resp{};
                resp.id = req.id;
                if (req.write) {
                    applyWrite(global_addr, req.size, req.wdata);
                    std::memset(resp.data, 0, sizeof(resp.data));
                } else {
                    buildMemResp(global_addr, resp.data);
                }
                mc_resps_[mc].push_back(resp);
            } else {
                stored_mc_req_[mc] = std::nullopt;
            }

            // Pop consumed response (if resp_valid was set last cycle)
            if (*p.resp_valid && !mc_resps_[mc].empty()) {
                mc_resps_[mc].pop_front();
            }
        }

        // Peripheral request
        if (sys->io_periph_req_ready && sys->io_periph_req_valid) {
            GlobalMemReq req{};
            req.id = sys->io_periph_req_bits_id;
            req.addr = sys->io_periph_req_bits_addr;
            req.write = sys->io_periph_req_bits_write;
            req.size = 5;
            std::memcpy(req.wdata, sys->io_periph_req_bits_wdata, MEM_BUS_WORDS * 4);
            stored_periph_req_ = req;
        } else {
            stored_periph_req_ = std::nullopt;
        }
        // Pop consumed peripheral response
        if (sys->io_periph_resp_valid && !periph_resps_.empty()) {
            periph_resps_.pop_front();
        }

        // ── Phase 2: Posedge ──
        sys->reset = false;
        sys->clock = true;
        Verilated::timeInc(1);
        sys->eval();
        if (tracing_ && tracer_) tracer_->dump(cycle_ * 2);

        // ── Phase 3: Drive signals for next cycle ──
        // req_ready = always 1 (flat memory, no backpressure)
""")
    for i in range(num_mc):
        f.write(f"        *mem_ports[{i}].req_ready = 1;\n")
    f.write("""        sys->io_periph_req_ready = 1;

        // Drive resp from internal queue front
        for (int mc = 0; mc < HARD_NUM_MC; ++mc) {
            auto &p = mem_ports[mc];
            if (!mc_resps_[mc].empty()) {
                auto &r = mc_resps_[mc].front();
                *p.resp_valid = 1;
                *p.resp_id = r.id;
                std::memcpy(p.resp_rdata, r.data, MEM_BUS_WORDS * 4);
            } else {
                *p.resp_valid = 0;
            }
        }
        if (!periph_resps_.empty()) {
            auto &r = periph_resps_.front();
            sys->io_periph_resp_valid = 1;
            sys->io_periph_resp_bits_id = r.id;
            std::memcpy(sys->io_periph_resp_bits_rdata, r.data, MEM_BUS_WORDS * 4);
        } else {
            sys->io_periph_resp_valid = 0;
        }

        // ── Phase 4: Negedge ──
        sys->clock = false;
        Verilated::timeInc(1);
        sys->eval();
        if (tracing_ && tracer_) tracer_->dump(cycle_ * 2 + 1);
    }
""")

    # mem(): just report stored requests for cosim comparison, ignore bus_in
    f.write("""
    void mem(const MemBusIn *bus_in, MemBusOut *bus_out) override {
        // Accept peripheral response from frontend
        if (bus_in[0].resp) {
            GlobalMemResp r{};
            r.id = bus_in[0].resp->id;
            std::memcpy(r.data, bus_in[0].resp->data, sizeof(r.data));
            periph_resps_.push_back(r);
        }
        // Report stored requests (captured in step()) for cosim comparison.
        // The hard backend self-serves MC memory in step(), so MC bus_in is ignored.
        bus_out[0].req = stored_periph_req_;
        for (int mc = 0; mc < HARD_NUM_MC; ++mc)
            bus_out[mc + 1].req = stored_mc_req_[mc];
    }
""")

    # printStats()
    f.write("    bool printStats(uint64_t, bool) override { return false; }\n")

    f.write("};\n")
